// Test migration tren Postgres THAT chay trong bo nho (PGlite): khong can Supabase / mang.
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { loadMigrations, MigrationRunner, type Migration } from "../lib/infra/migrations/MigrationRunner.ts";
import type { SqlClient } from "../lib/infra/migrations/SqlClient.ts";
import { PROJECT_ROOT } from "../lib/paths.ts";

const MIGRATIONS = loadMigrations(path.join(PROJECT_ROOT, "database", "migrations"));

// SqlClient tren PGlite
function pglite(db: PGlite): SqlClient {
  return {
    exec: async sql => { await db.exec(sql); },
    query: async <T>(sql: string, params: unknown[] = []) => (await db.query<T>(sql, params)).rows,
    close: () => db.close()
  };
}

// Database giong Supabase: co san vai tro anon / authenticated
async function supabaseLike(): Promise<{ db: PGlite; sql: SqlClient }> {
  const db = new PGlite();
  await db.exec("create role anon; create role authenticated;");
  return { db, sql: pglite(db) };
}

async function columns(sql: SqlClient, table: string): Promise<string[]> {
  const rows = await sql.query<{ column_name: string }>(
    "select column_name from information_schema.columns where table_name = $1 order by column_name", [table]);
  return rows.map(r => r.column_name);
}

test("file migration đặt tên đúng mẫu, đánh số liên tục", () => {
  assert.ok(MIGRATIONS.length >= 4);
  MIGRATIONS.forEach((m, i) => assert.equal(Number(m.version), i + 1, `${m.file} sai thứ tự`));
});

test("database trống: áp đủ migration, chạy lại không áp trùng", async () => {
  const { sql } = await supabaseLike();
  const runner = new MigrationRunner(sql, MIGRATIONS);

  const first = await runner.migrate();
  assert.equal(first.length, MIGRATIONS.length);
  assert.deepEqual(await columns(sql, "exams"), ["assigned_to", "created_at", "duration_minutes", "entry_password", "id", "proctor_code", "questions", "require_password", "require_seb", "seb_quit_password", "title"]);
  assert.ok((await columns(sql, "exam_results")).includes("action_logs"));
  assert.ok((await columns(sql, "exam_events")).includes("type"));
  assert.deepEqual(await columns(sql, "app_settings"), ["key", "value"]);

  assert.deepEqual(await runner.migrate(), []);
  const status = await runner.status();
  assert.equal(status.applied.length, MIGRATIONS.length);
  assert.equal(status.pending.length, 0);
  await sql.close();
});

test("database cũ tạo tay (thiếu cột, policy mở công khai): migration nâng cấp, giữ dữ liệu, đóng quyền", async () => {
  const { sql } = await supabaseLike();
  // Trang thai giong Supabase hien tai: exam_results kieu cu, exams chua co proctor_code, policy "Allow ..." mo
  await sql.exec(`
    create table exam_results (id bigint generated by default as identity primary key, student_name text not null,
      score numeric, total_questions int, duration_minutes int, submitted_at timestamptz default now());
    insert into exam_results (student_name, score) values ('nguyen', 2.4);
    create table exams (id bigint generated by default as identity primary key, title text not null,
      duration_minutes int default 45, assigned_to text default 'all', questions jsonb not null default '[]', created_at timestamptz default now());
    insert into exams (title) values ('Đề cũ');
    alter table exams enable row level security;
    create policy "Allow read exams" on exams for select using (true);
    grant select on exams to anon;
  `);

  await new MigrationRunner(sql, MIGRATIONS).migrate();

  assert.ok((await columns(sql, "exam_results")).includes("exam_id"));
  assert.ok((await columns(sql, "exams")).includes("proctor_code"));
  assert.deepEqual(await sql.query("select student_name, score::float as score from exam_results"), [{ student_name: "nguyen", score: 2.4 }]);
  assert.deepEqual(await sql.query("select title from exams"), [{ title: "Đề cũ" }]);
  assert.deepEqual(await sql.query("select policyname from pg_policies where tablename = 'exams'"), []);
  const [{ allowed }] = await sql.query<{ allowed: boolean }>("select has_table_privilege('anon', 'exams', 'select') as allowed");
  assert.equal(allowed, false);
  await sql.close();
});

test("migration đã chạy mà file bị sửa → báo lỗi, không chạy tiếp", async () => {
  const { sql } = await supabaseLike();
  await new MigrationRunner(sql, MIGRATIONS.slice(0, 2)).migrate();
  const edited: Migration[] = MIGRATIONS.map((m, i) => (i === 0 ? { ...m, sql: m.sql + "\n-- sua", checksum: "khac" } : m));
  await assert.rejects(new MigrationRunner(sql, edited).migrate(), /bị sửa/);
  assert.equal((await new MigrationRunner(sql, MIGRATIONS).status()).applied.length, 2);
  await sql.close();
});

test("migration lỗi giữa chừng → rollback toàn bộ file đó, không ghi là đã chạy", async () => {
  const { sql } = await supabaseLike();
  const broken: Migration = { version: "9999", name: "loi", file: "9999_loi.sql", checksum: "x", sql: "create table bang_moi (id int); select * from bang_khong_ton_tai;" };
  await assert.rejects(new MigrationRunner(sql, [...MIGRATIONS, broken]).migrate(), /9999_loi\.sql lỗi, đã rollback/);
  const [{ exists }] = await sql.query<{ exists: boolean }>("select to_regclass('bang_moi') is not null as exists");
  assert.equal(exists, false);
  const status = await new MigrationRunner(sql, [...MIGRATIONS, broken]).status();
  assert.equal(status.applied.length, MIGRATIONS.length);
  assert.deepEqual(status.pending.map(m => m.version), ["9999"]);
  await sql.close();
});

test("checksum không phụ thuộc xuống dòng Windows/Linux; tên file sai mẫu bị từ chối", async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "mig-"));
  fs.writeFileSync(path.join(dir, "0001_a.sql"), "select 1;\r\nselect 2;\r\n");
  fs.writeFileSync(path.join(dir, "0002_b.sql"), "select 1;\nselect 2;\n");
  const [a, b] = loadMigrations(dir);
  assert.equal(a.checksum, b.checksum);
  fs.writeFileSync(path.join(dir, "3_Sai Ten.sql"), "");
  assert.throws(() => loadMigrations(dir), /sai mẫu/);
  fs.rmSync(dir, { recursive: true });
});

test("mã đề 5 chữ số ngẫu nhiên: đề cũ được đổi mã, kết quả / sự cố trỏ theo; đề mới tự có mã 5 số", async () => {
  const { sql } = await supabaseLike();
  const before = MIGRATIONS.filter(m => Number(m.version) < 6);
  await new MigrationRunner(sql, before).migrate();
  // Du lieu kieu cu: de ma 4, 5 + ket qua / su co tro toi
  await sql.exec(`
    insert into exams (id, title) values (4, 'Đề 4'), (5, 'Đề 5');
    insert into exam_results (student_name, exam_id) values ('an', 4), ('binh', 5), ('chi', 5);
    insert into exam_events (student_name, exam_id, type) values ('an', 4, 'MO_KHOA');
  `);

  await new MigrationRunner(sql, MIGRATIONS).migrate();

  const exams = await sql.query<{ id: string; title: string }>("select id::text, title from exams order by title");
  assert.equal(exams.length, 2);
  for (const e of exams) assert.match(e.id, /^[1-9]\d{4}$/);
  const [de4, de5] = exams.map(e => e.id);
  assert.deepEqual(await sql.query("select student_name, exam_id::text as exam_id from exam_results order by student_name"),
    [{ student_name: "an", exam_id: de4 }, { student_name: "binh", exam_id: de5 }, { student_name: "chi", exam_id: de5 }]);
  assert.deepEqual(await sql.query("select exam_id::text as exam_id from exam_events"), [{ exam_id: de4 }]);

  // De moi: database tu cap ma 5 so, khong trung
  const created = await sql.query<{ id: string }>("insert into exams (title) select 'Mới ' || g from generate_series(1, 50) g returning id::text");
  for (const c of created) assert.match(c.id, /^[1-9]\d{4}$/);
  assert.equal(new Set(created.map(c => c.id)).size, 50);
  await assert.rejects(sql.exec("insert into exams (id, title) values (7, 'sai')"), /exams_id_five_digits/);
  await sql.close();
});
