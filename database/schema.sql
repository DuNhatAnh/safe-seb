-- server (lib/api.js) bang khoa service_role (bo qua RLS). Vi vay o day bat RLS va
-- KHONG tao policy nao cho anon/authenticated -> khoa cong khai (publishable/anon)
-- khong doc duoc dap an, khong sua duoc diem, khong ghi duoc gi.
