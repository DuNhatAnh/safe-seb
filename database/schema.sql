-- Bang de thi (exams). questions chua ca dap an -> chi server doc.
create table if not exists exams (
  id bigint generated by default as identity primary key,
  title text not null,
  duration_minutes int default 45,
  assigned_to text default 'all',
  questions jsonb not null default '[]'::jsonb,
  created_at timestamp with time zone default now()
);

-- Bo sung cac cot cho bang exam_results
alter table exam_results add column if not exists exam_id bigint;
alter table exam_results add column if not exists answers jsonb default '[]'::jsonb;
alter table exam_results add column if not exists action_logs jsonb default '[]'::jsonb;

-- Tim nhanh bai da nop theo de + thi sinh (moi de chi nop 1 lan, server kiem tra)
create index if not exists exam_results_exam_student_idx on exam_results (exam_id, student_name);

-- Cau hinh he thong (vd: key 'exam_templates' = cac mau cau truc de Phan I, II, III...)
create table if not exists app_settings (
  key text primary key,
  value jsonb not null
);

-- Su co phong thi: moi lan nhap mat khau giam thi de thi sinh thoat (dung hoac sai)
create table if not exists exam_events (
  id bigint generated by default as identity primary key,
  exam_id bigint,
  exam_title text,
  student_name text not null,
  type text not null,            -- THOAT_KHAN_CAP | THOAT_UNG_DUNG | SAI_MAT_KHAU
  detail text,
  action_logs jsonb default '[]'::jsonb,
  created_at timestamp with time zone default now()
);

-- Bat RLS + go bo moi policy mo cong khai cu
alter table exams enable row level security;
alter table exam_results enable row level security;
alter table app_settings enable row level security;
alter table exam_events enable row level security;

drop policy if exists "Allow read exams" on exams;
drop policy if exists "Allow insert exams" on exams;
drop policy if exists "Allow update exams" on exams;
drop policy if exists "Allow delete exams" on exams;

drop policy if exists "Allow read exam_results" on exam_results;
drop policy if exists "Allow insert exam_results" on exam_results;
drop policy if exists "Allow update exam_results" on exam_results;

drop policy if exists "Allow read app_settings" on app_settings;
drop policy if exists "Allow insert app_settings" on app_settings;
drop policy if exists "Allow update app_settings" on app_settings;

drop policy if exists "Allow read exam_events" on exam_events;
drop policy if exists "Allow insert exam_events" on exam_events;

-- Them 1 lop nua: thu hoi quyen bang cua vai tro cong khai
revoke all on exams, exam_results, app_settings, exam_events from anon, authenticated;
