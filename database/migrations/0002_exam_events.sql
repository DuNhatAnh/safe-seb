-- Su co phong thi: moi lan giam thi nhap ma (dung / sai) de thi sinh thoat, mo khoa, lam lai.
create table if not exists exam_events (
  id bigint generated by default as identity primary key,
  exam_id bigint,
  exam_title text,
  student_name text not null,
  type text not null,            -- THOAT_KHAN_CAP | THOAT_UNG_DUNG | SAI_MAT_KHAU | CHO_LAM_LAI | MO_KHOA
  detail text,
  action_logs jsonb default '[]'::jsonb,
  created_at timestamp with time zone default now()
);

-- Dem luot lam lai (CHO_LAM_LAI) theo de + thi sinh
create index if not exists exam_events_exam_student_type_idx on exam_events (exam_id, student_name, type);
