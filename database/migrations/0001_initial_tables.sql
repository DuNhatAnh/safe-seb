-- Bang goc: de thi, ket qua, cau hinh he thong.
-- Viet "if not exists" de ap duoc len database da tao tay truoc khi co migration.

create table if not exists exams (
  id bigint generated by default as identity primary key,
  title text not null,
  duration_minutes int default 45,
  assigned_to text default 'all',
  questions jsonb not null default '[]'::jsonb,
  created_at timestamp with time zone default now()
);

create table if not exists exam_results (
  id bigint generated by default as identity primary key,
  student_name text not null,
  score numeric default 0,
  total_questions int default 0,
  duration_minutes int,
  submitted_at timestamp with time zone default now()
);

-- Cot bo sung sau (database cu tao bang truoc khi co cac cot nay)
alter table exam_results add column if not exists exam_id bigint;
alter table exam_results add column if not exists answers jsonb default '[]'::jsonb;
alter table exam_results add column if not exists action_logs jsonb default '[]'::jsonb;

-- Tim nhanh cac lan nop theo de + thi sinh (dem luot lam bai)
create index if not exists exam_results_exam_student_idx on exam_results (exam_id, student_name);

-- Cau hinh he thong (vd: key 'exam_templates' = mau cau truc de Phan I, II, III...)
create table if not exists app_settings (
  key text primary key,
  value jsonb not null
);
